# 各人数配置的角色池（角色 -> 数量）
CONFIGS = {
    6: {"狼人": 1, "预言家": 1, "村民": 4},
    9: {"狼人": 3, "预言家": 1, "女巫": 1, "猎人": 1, "村民": 3},
    12: {"狼人": 4, "预言家": 1, "女巫": 1, "猎人": 1, "守卫": 1, "村民": 4},
}


def get_role_config(player_count: int) -> dict:
    """返回指定人数的角色配置（角色 -> 数量）。"""
    return CONFIGS.get(player_count, CONFIGS[9])


def get_camp(role: str) -> str:
    """返回角色阵营。"""
    return ROLES.get(role, {}).get("阵营", "好人阵营")


def is_wolf(role: str) -> bool:
    return get_camp(role) == "狼人阵营"


def count_of(role: str) -> int:
    """角色在 9 人标准局中的数量（无则 1）。"""
    return ROLES.get(role, {}).get("数量", 1)
